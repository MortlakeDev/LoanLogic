from __future__ import annotations

from typing import Any

REF = "Reference implementation (tools/reference)"
SPEC_EX = "SPEC-finance §5.6"


def loan(**fields: Any) -> dict[str, Any]:
    return fields


def fee(fee_id: str, kind: str, calc: str, value: str, *, in_apr: bool = True,
        financing: str | None = None) -> dict[str, Any]:
    item: dict[str, Any] = {"id": fee_id, "kind": kind, "calc": calc, "value": value}
    if financing is not None:
        item["financing"] = financing
    item["inApr"] = in_apr
    return item


def monthly_flows(start: tuple[int, int, int], inflow: str, outflow: str, count: int) -> list[dict[str, Any]]:
    year, month, day = start
    flows = [{"period": 0, "date": f"{year:04d}-{month:02d}-{day:02d}", "amount": inflow}]
    for k in range(1, count + 1):
        y, m0 = divmod(month - 1 + k, 12)
        flows.append(
            {"period": k, "date": f"{year + y:04d}-{m0 + 1:02d}-{day:02d}", "amount": outflow}
        )
    return flows


