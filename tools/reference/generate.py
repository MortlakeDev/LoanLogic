"""Generates the core golden vectors in tests/vectors/core from cases.py.

    python tools/reference/generate.py          # write tests/vectors/core/*.json
    python tools/reference/generate.py --check  # fail if any file is missing or stale

Requires Python 3.10+ and nothing else.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from cases import CASES  # noqa: E402
from loanlogic_ref import calculate_loan  # noqa: E402
from loanlogic_ref.rates import compute_cashflow_rates  # noqa: E402

ROOT = HERE.parent.parent
OUT_DIR = ROOT / "tests" / "vectors" / "core"
SCHEMA_VERSION = 1
# Keys whose array items are written one per line, each item on a single line.
ONE_LINE_ITEMS = {"rows", "flows"}


def _dump(value: Any, indent: int, key: str | None = None) -> str:
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [
            f"{inner}{json.dumps(k, ensure_ascii=False)}: {_dump(v, indent + 1, k)}"
            for k, v in value.items()
        ]
        return "{\n" + ",\n".join(items) + "\n" + pad + "}"
    if isinstance(value, list):
        if not value:
            return "[]"
        if key in ONE_LINE_ITEMS:
            items = [
                inner + json.dumps(v, ensure_ascii=False, separators=(", ", ": ")) for v in value
            ]
        else:
            items = [inner + _dump(v, indent + 1) for v in value]
        return "[\n" + ",\n".join(items) + "\n" + pad + "]"
    return json.dumps(value, ensure_ascii=False)


def build(case: dict[str, Any]) -> dict[str, Any]:
    kind = case.get("kind", "loan")
    if kind == "loan":
        expected = calculate_loan(case["input"])
    elif kind == "cashflows":
        expected = compute_cashflow_rates(case["input"])
    else:
        raise ValueError(f"unknown kind {kind!r}")
    if expected.get("ok"):
        ordered = {"ok": True}
        if kind == "loan":
            ordered["warnings"] = expected["warnings"]
            ordered["summary"] = expected["summary"]
        ordered["rates"] = expected["rates"]
        if kind == "loan":
            ordered["rows"] = expected["rows"]
        expected = ordered
    return {
        "schemaVersion": SCHEMA_VERSION,
        "id": case["id"],
        "description": case["description"],
        "source": case["source"],
        "kind": kind,
        "input": case["input"],
        "expected": expected,
    }


def render(case: dict[str, Any]) -> str:
    return _dump(build(case), 0) + "\n"


def render_index() -> str:
    """tests/vectors/core/README.md: a generated table of all core vectors."""
    lines = [
        "<!-- Generated by tools/reference/generate.py from tools/reference/cases.py. Do not edit. -->",
        "",
        "# Core golden vectors (M1)",
        "",
        "Generated by the reference implementation in [`tools/reference`](../../../tools/reference).",
        "Format and comparison rules: [`docs/SPEC-finance.md`](../../../docs/SPEC-finance.md) §14.",
        "",
        "| Vector | Kind | What it checks | Source |",
        "|---|---|---|---|",
    ]
    for case in CASES:
        cells = [
            f"[`{case['id']}`]({case['id']}.json)",
            case.get("kind", "loan"),
            case["description"],
            case["source"],
        ]
        lines.append("| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify instead of writing")
    args = parser.parse_args()

    ids = [case["id"] for case in CASES]
    if len(ids) != len(set(ids)):
        print("duplicate case ids", file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    expected_files = {f"{case_id}.json" for case_id in ids}
    problems: list[str] = []
    for case in CASES:
        text = render(case)
        path = OUT_DIR / f"{case['id']}.json"
        if args.check:
            if not path.exists():
                problems.append(f"missing: {path.relative_to(ROOT)}")
            elif path.read_text(encoding="utf-8") != text:
                problems.append(f"stale: {path.relative_to(ROOT)}")
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    index_path = OUT_DIR / "README.md"
    index_text = render_index()
    if args.check:
        if not index_path.exists() or index_path.read_text(encoding="utf-8") != index_text:
            problems.append(f"stale: {index_path.relative_to(ROOT)}")
    else:
        index_path.write_text(index_text, encoding="utf-8", newline="\n")
    for extra in sorted(p.name for p in OUT_DIR.glob("*.json")):
        if extra not in expected_files:
            problems.append(f"not generated by cases.py: tests/vectors/core/{extra}")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    action = "verified" if args.check else "wrote"
    print(f"{action} {len(CASES)} vectors in {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
